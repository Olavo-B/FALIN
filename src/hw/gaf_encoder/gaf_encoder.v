/* Description: Hand-written synthesizable Verilog GAF (Gramian Angular     */
/* Summation Field) encoder, replacing the earlier Vitis HLS C++ attempt so */
/* it can be run through an open-source flow (Yosys) instead of Vivado/     */
/* Vitis. Target: ElectricDevices (seq_len = 96 = the 96x96 target          */
/* resolution, so no resize/interpolation stage is needed).                 */
/*                                                                          */
/* Algorithm: gaf[i,j] = cos(phi_i + phi_j)                                 */
/*          = cos_phi[i]*cos_phi[j] - sin_phi[i]*sin_phi[j]                 */
/* computed without ever evaluating arccos/cos/sin, since                   */
/* cos(arccos(x)) = x and sin(arccos(x)) = sqrt(1 - x^2). cos_phi is the    */
/* normalized signal directly; sin_phi comes from a precomputed ROM         */
/* (sin_phi_rom.hex, generated by gen_sin_phi_rom.py) instead of a sqrt     */
/* unit.                                                                    */
/*                                                                          */
/* IMPORTANT (see gen_sin_phi_rom.py header): sqrt(1-x^2) has a vertical    */
/* tangent at x=+-1, and every window's own min/max sample lands exactly    */
/* there after normalization, so the ROM address needs more precision      */
/* (12 bits, Q1.11) than the 8-bit final GAF output (Q1.7) - rounding is    */
/* only done once, at the very end, after the outer product. Exhaustive    */
/* check against all 7711 real ElectricDevices test windows (bit-accurate  */
/* Python model of this exact design): worst-case abs error 0.0114.        */
/*                                                                          */
/* Architecture: a 3-stage FSM, one row/sample per cycle (not a full        */
/* unroll, not a fully scalar one-cycle-per-output-element design either):  */
/*   MINMAX      - 96 cycles, sequential min/max scan.                      */
/*   NORMALIZE   - 96 cycles, one division + one ROM lookup per sample,     */
/*                 filling the cos_phi/sin_phi register files.              */
/*   OUTER_PROD  - 96 cycles, one row per cycle: cos_phi[i]/sin_phi[i] are   */
/*                 broadcast scalars, multiplied in parallel against the    */
/*                 full 96-entry cos_phi/sin_phi register files (192        */
/*                 parallel 12x12 multipliers) to produce one full output   */
/*                 row per cycle.                                          */
/*                                                                          */
/* Ports are flattened 1D vectors (signal_in_flat / gaf_out_flat) rather    */
/* than unpacked SystemVerilog array ports: Yosys's Verilog frontend        */
/* rejects `input ... foo [0:N-1]` directly in the ANSI port list. Internal */
/* unpacked arrays (signal_in/gaf_out below) are unpacked/packed right at   */
/* the boundary and used everywhere else for readability.                  */
/*                                                                          */
/* See Task 6 of misc/docs/fpga_implementation_plan.md.                    */
/*****************************************************************************/

`timescale 1ns / 1ps

module gaf_encoder #(
    parameter SEQ_LEN    = 96,
    parameter RAW_WIDTH  = 16,  // raw input sample: Q5.10 (5 int bits incl. sign, 10 frac)
    parameter RAW_FRAC   = 10,
    parameter NORM_WIDTH = 12,  // x_norm / ROM address: Q1.11
    parameter NORM_FRAC  = 11,
    parameter OUT_WIDTH  = 8,   // GAF output: Q1.7 (matches the INT8 CNN input, Task 5)
    parameter OUT_FRAC   = 7
) (
    input  wire                                    clk,
    input  wire                                    rst_n,
    input  wire                                    start,
    input  wire signed [SEQ_LEN*RAW_WIDTH-1:0]     signal_in_flat,
    output reg                                     done,
    output reg  signed [SEQ_LEN*SEQ_LEN*OUT_WIDTH-1:0] gaf_out_flat
);

    // ------------------------------------------------------------------
    // Unpack/pack the flattened ports into internal arrays used everywhere
    // else below (only the port declarations themselves need to be flat).
    // ------------------------------------------------------------------
    wire signed [RAW_WIDTH-1:0] signal_in [0:SEQ_LEN-1];
    reg  signed [OUT_WIDTH-1:0] gaf_out   [0:SEQ_LEN-1][0:SEQ_LEN-1];

    genvar gi;
    generate
        for (gi = 0; gi < SEQ_LEN; gi = gi + 1) begin : gen_unpack_in
            assign signal_in[gi] = signal_in_flat[(gi+1)*RAW_WIDTH-1 -: RAW_WIDTH];
        end
    endgenerate

    // Pack gaf_out (2D unpacked array, written by the clocked generate
    // block below) into the flat output port. Deliberately ONE always
    // block with a procedural nested for-loop rather than a 96x96
    // generate-of-always-blocks: 9216 separate always blocks made iverilog
    // elaboration extremely slow (each is a distinct process the simulator
    // has to schedule/track); a single process with a bounded loop is the
    // standard way to pack an unpacked array into a flat bus.
    //
    // Clocked (posedge clk), not combinational (@*): implicit sensitivity
    // to every element of a large 2D unpacked array read through a
    // procedural for-loop is a known rough edge in some Verilog simulators
    // (the tool may not always re-trigger correctly on every element
    // write). An unconditional clocked mirror sidesteps that entirely -
    // gaf_out_flat trails gaf_out by one cycle, which is harmless since it
    // is only read well after `done`.
    integer pk_i, pk_j;
    always @(posedge clk) begin
        for (pk_i = 0; pk_i < SEQ_LEN; pk_i = pk_i + 1) begin
            for (pk_j = 0; pk_j < SEQ_LEN; pk_j = pk_j + 1) begin
                gaf_out_flat[((pk_i*SEQ_LEN+pk_j)+1)*OUT_WIDTH-1 -: OUT_WIDTH] <= gaf_out[pk_i][pk_j];
            end
        end
    end

    // ------------------------------------------------------------------
    // ROM: sin_phi_rom.hex generated by gen_sin_phi_rom.py. Indexed by
    // x_norm's raw NORM_WIDTH-bit two's complement pattern.
    // ------------------------------------------------------------------
    localparam ROM_DEPTH = (1 << NORM_WIDTH);
    reg [NORM_WIDTH-1:0] sin_phi_rom [0:ROM_DEPTH-1];
    initial $readmemh("sin_phi_rom.hex", sin_phi_rom);

    // ------------------------------------------------------------------
    // FSM states
    // ------------------------------------------------------------------
    localparam ST_IDLE       = 3'd0;
    localparam ST_MINMAX     = 3'd1;
    localparam ST_NORM_INIT  = 3'd2;
    localparam ST_NORM       = 3'd3;
    localparam ST_OUTER      = 3'd4;
    localparam ST_DONE       = 3'd5;

    reg [2:0] state;
    reg [7:0] idx;  // shared row/sample counter for all three stages (0..95)

    reg signed [RAW_WIDTH-1:0] min_val, max_val;
    reg signed [RAW_WIDTH-1:0] range_val;

    reg signed [NORM_WIDTH-1:0] cos_phi [0:SEQ_LEN-1];
    reg signed [NORM_WIDTH-1:0] sin_phi [0:SEQ_LEN-1];

    // Division scratch registers for the NORMALIZE stage.
    // x_norm_raw = (x_diff * 2^(NORM_FRAC+1)) / range_val - 2^NORM_FRAC
    // represents 2*(x_diff/range) - 1 in Q1.NORM_FRAC. RAW_FRAC cancels
    // between numerator and denominator, so no rescaling to "real units"
    // is needed - both x_diff and range_val stay in raw fixed-point counts.
    reg signed [31:0] numerator;
    reg signed [31:0] x_norm_raw;
    reg signed [NORM_WIDTH-1:0] x_norm_q;

    // ------------------------------------------------------------------
    // OUTER_PROD stage datapath: broadcast row i against the full
    // register file in parallel (192 multipliers total: 96 columns x 2).
    //
    // cos_prod/sin_prod are Q2.(2*NORM_FRAC) (product of two Q1.NORM_FRAC
    // operands - always 2x the operand width, no exceptions). diff keeps
    // the same 2*NORM_FRAC fractional-bit scale; SHIFT_AMOUNT moves the
    // binary point down to OUT_FRAC, rounding (round-half-up, via BIAS)
    // once, only at this final step, then saturating to the OUT_WIDTH
    // signed range with plain integer comparisons (not manual bit-pattern
    // overflow checks - simpler and easier to get right).
    // ------------------------------------------------------------------
    localparam SHIFT_AMOUNT = 2*NORM_FRAC - OUT_FRAC;               // 15 for the default widths
    localparam signed [2*NORM_WIDTH:0] ROUND_BIAS = 1 <<< (SHIFT_AMOUNT - 1);
    localparam signed [2*NORM_WIDTH:0] OUT_MAX = (1 <<< (OUT_WIDTH-1)) - 1;
    localparam signed [2*NORM_WIDTH:0] OUT_MIN = -(1 <<< (OUT_WIDTH-1));

    genvar gj;
    generate
        for (gj = 0; gj < SEQ_LEN; gj = gj + 1) begin : gen_outer_col
            wire signed [2*NORM_WIDTH-1:0] cos_prod;
            wire signed [2*NORM_WIDTH-1:0] sin_prod;
            wire signed [2*NORM_WIDTH:0]   diff;       // +1 bit headroom for the subtraction
            wire signed [2*NORM_WIDTH:0]   rounded;    // diff + round-half-up bias
            wire signed [2*NORM_WIDTH:0]   shifted;    // rounded, binary point moved to OUT_FRAC
            wire signed [OUT_WIDTH-1:0]    saturated;

            assign cos_prod = cos_phi[idx] * cos_phi[gj];
            assign sin_prod = sin_phi[idx] * sin_phi[gj];
            assign diff     = cos_prod - sin_prod;
            assign rounded  = diff + ROUND_BIAS;
            assign shifted  = rounded >>> SHIFT_AMOUNT;

            // GAF is mathematically bounded to [-1, 1) already (see header),
            // so this saturation is just a guard rail, not expected to
            // trigger under normal operation.
            assign saturated = (shifted > OUT_MAX) ? OUT_MAX[OUT_WIDTH-1:0] :
                               (shifted < OUT_MIN) ? OUT_MIN[OUT_WIDTH-1:0] :
                               shifted[OUT_WIDTH-1:0];

            always @(posedge clk) begin
                if (state == ST_OUTER) begin
                    gaf_out[idx][gj] <= saturated;
                end
            end
        end
    endgenerate

    // ------------------------------------------------------------------
    // Main FSM
    // ------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            state     <= ST_IDLE;
            done      <= 1'b0;
            idx       <= 8'd0;
            min_val   <= {RAW_WIDTH{1'b0}};
            max_val   <= {RAW_WIDTH{1'b0}};
            range_val <= {RAW_WIDTH{1'b0}};
        end else begin
            case (state)

                ST_IDLE: begin
                    done <= 1'b0;
                    if (start) begin
                        min_val <= signal_in[0];
                        max_val <= signal_in[0];
                        idx     <= 8'd1;
                        state   <= ST_MINMAX;
                    end
                end

                // --- Stage 1: sequential min/max scan, 1 sample/cycle ---
                ST_MINMAX: begin
                    if (signal_in[idx] < min_val) min_val <= signal_in[idx];
                    if (signal_in[idx] > max_val) max_val <= signal_in[idx];

                    if (idx == SEQ_LEN - 1) begin
                        idx   <= 8'd0;
                        state <= ST_NORM_INIT;
                    end else begin
                        idx <= idx + 8'd1;
                    end
                end

                // --- Latch range = max - min once, before normalizing ---
                ST_NORM_INIT: begin
                    range_val <= max_val - min_val;
                    idx       <= 8'd0;
                    state     <= ST_NORM;
                end
                
                // --- Stage 2: normalize + ROM lookup, 1 sample/cycle ---
                ST_NORM: begin
                    if (range_val == 0) begin
                        cos_phi[idx] <= {NORM_WIDTH{1'b0}};
                        sin_phi[idx] <= sin_phi_rom[0]; // x_norm=0 -> sin_phi=1.0 (saturated)
                    end else begin
                        numerator  = (signal_in[idx] - min_val) <<< (NORM_FRAC + 1);
                        x_norm_raw = numerator / range_val;
                        
                        // Lógica de Saturação para evitar o overflow
                        if ((x_norm_raw - (1 <<< NORM_FRAC)) > ((1 <<< NORM_FRAC) - 1)) begin
                            x_norm_q = (1 <<< NORM_FRAC) - 1; // Satura em +0.9995
                        end else begin
                            x_norm_q = x_norm_raw - (1 <<< NORM_FRAC);
                        end
                        
                        cos_phi[idx] <= x_norm_q;
                        sin_phi[idx] <= sin_phi_rom[x_norm_q[NORM_WIDTH-1:0]];
                    end

                    // ---> PARTE CRÍTICA QUE FAZ O HARDWARE AVANÇAR <---
                    if (idx == SEQ_LEN - 1) begin
                        idx   <= 8'd0;
                        state <= ST_OUTER; // Terminou de normalizar, vai gerar a imagem
                    end else begin
                        idx <= idx + 8'd1; // Avança para a próxima amostra da janela
                    end
                end

                // --- Stage 3: outer product, 1 full row/cycle (see generate block above) ---
                ST_OUTER: begin
                    if (idx == SEQ_LEN - 1) begin
                        state <= ST_DONE;
                    end else begin
                        idx <= idx + 8'd1;
                    end
                end

                ST_DONE: begin
                    done  <= 1'b1;
                    state <= ST_IDLE;
                end

                default: state <= ST_IDLE;
            endcase
        end
    end

endmodule
