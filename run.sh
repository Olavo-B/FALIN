#!/bin/bash
# /*****************************************************************************/
# * File: run.sh
# * Author: Olavo Alves Barros Silva
# * Contact: olavo.barros@ufv.com
# * Date: 2026-07-24
# * Description: Runs the hardware validation pipeline (QAT fine-tune ->
# * export CNN weights/testbench -> Icarus Verilog simulation) for every
# * dataset in config.json's "datasets" list, or a subset given as arguments.
# * Requires results/<dataset>/run_1/FalinCNN_checkpoint.pth to already exist
# * for each dataset (i.e. `python src/sw/main.py` must have been run first -
# * see Task 8b of misc/docs/fpga_implementation_plan.md).
# *
# * Usage:
# *   ./run.sh                  # all datasets in config.json
# *   ./run.sh Wafer FordA      # only these datasets
# /*****************************************************************************/

# Colors for output (same convention as install.sh/activate.sh)
RED='\033[0;31m'
GREEN='\033[0;32m'
GOLD='\033[1;33m'
BLUE='\033[0;34m'
BOLD='\033[1m'
RESET='\033[0m'

echo_error()   { echo -e "${RED}${BOLD}[ERROR]${RESET} $1"; }
echo_success() { echo -e "${GREEN}${BOLD}[SUCCESS]${RESET} $1"; }
echo_info()    { echo -e "${BLUE}${BOLD}[INFO]${RESET} $1"; }
echo_warning() { echo -e "${GOLD}${BOLD}[WARNING]${RESET} $1"; }

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SW_DIR="$REPO_ROOT/src/sw"
HW_DIR="$REPO_ROOT/src/hw/cnn"

# Activate the venv if it isn't already (same pattern as activate.sh)
if [[ -z "${VIRTUAL_ENV:-}" && -d "$REPO_ROOT/.venv" ]]; then
    source "$REPO_ROOT/.venv/bin/activate"
fi

# Dataset selection: CLI args override config.json's full list
if [[ $# -gt 0 ]]; then
    DATASETS=("$@")
else
    mapfile -t DATASETS < <(python -c "
import json
with open('$REPO_ROOT/config.json') as f:
    print('\n'.join(json.load(f)['datasets']))
")
fi

echo_info "Datasets to process: ${DATASETS[*]}"

FAILED=()
PASSED=()

for DATASET in "${DATASETS[@]}"; do
    echo ""
    echo "=============================================="
    echo_info "[$DATASET] Starting hardware validation pipeline"
    echo "=============================================="

    FLOAT_CKPT="$REPO_ROOT/results/$DATASET/run_1/FalinCNN_checkpoint.pth"
    if [[ ! -f "$FLOAT_CKPT" ]]; then
        echo_warning "[$DATASET] SKIP: $FLOAT_CKPT not found - run 'python src/sw/main.py' first."
        FAILED+=("$DATASET (missing float checkpoint)")
        continue
    fi

    echo_info "[$DATASET] QAT fine-tuning..."
    if ! (cd "$SW_DIR" && python qat_finetune.py "$DATASET"); then
        echo_error "[$DATASET] QAT fine-tuning failed."
        FAILED+=("$DATASET (qat_finetune.py failed)")
        continue
    fi

    echo_info "[$DATASET] Exporting CNN weights + testbench vectors..."
    if ! (cd "$HW_DIR" && python export_cnn_weights.py "$DATASET"); then
        echo_error "[$DATASET] export_cnn_weights.py failed."
        FAILED+=("$DATASET (export_cnn_weights.py failed)")
        continue
    fi

    RUN_SCRIPT="$REPO_ROOT/results/$DATASET/hw/run_sim.sh"
    if [[ ! -f "$RUN_SCRIPT" ]]; then
        echo_error "[$DATASET] $RUN_SCRIPT was not generated by export_cnn_weights.py."
        FAILED+=("$DATASET (missing run_sim.sh)")
        continue
    fi

    echo_info "[$DATASET] Compiling + simulating (this can take a few minutes)..."
    if ! (cd "$HW_DIR" && bash "$RUN_SCRIPT"); then
        echo_error "[$DATASET] Verilog build/simulation failed."
        FAILED+=("$DATASET (run_sim.sh failed)")
        continue
    fi

    echo_success "[$DATASET] Done."
    PASSED+=("$DATASET")
done

echo ""
echo "=============================================="
echo_info "Summary: ${#PASSED[@]} passed, ${#FAILED[@]} failed/skipped."
if [[ ${#PASSED[@]} -gt 0 ]]; then
    echo_success "Passed: ${PASSED[*]}"
fi
if [[ ${#FAILED[@]} -gt 0 ]]; then
    echo_error "Failed/skipped:"
    printf '  - %s\n' "${FAILED[@]}"
fi
echo_info "Accuracy table: results/hw_validation_summary.csv"
